"""Generate mobile/js/catalog.js from the single source of truth (backend/docmind/knowledge/catalog.py)."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "backend"))
from docmind.assistant.texts import T  # noqa: E402
from docmind.knowledge import catalog as c  # noqa: E402

data = {
    "CATEGORIES": [{"key": k, "en": en, "he": he, "icon": icon} for k, en, he, icon in c.CATEGORIES],
    "DOC_TYPES": c.DOC_TYPES, "REQUEST_ALIASES": c.REQUEST_ALIASES, "PROCESSES": c.PROCESSES,
    "ACQUISITION": c.ACQUISITION, "KNOWN_ISSUERS": c.KNOWN_ISSUERS, "TEXTS": T,
}
out = root / "mobile/js/catalog.js"
out.write_text("// GENERATED by scripts/export_catalog.py from backend/docmind/knowledge/catalog.py, do not edit.\n"
               "export default " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print("wrote", out, out.stat().st_size, "bytes")
